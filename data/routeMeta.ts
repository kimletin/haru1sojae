/** 주소 첫 조각으로 제목을 찾는다. 홈(빈 값)은 HOME_TITLE, 모르는 주소는 null */
export function routeTitle(slug?: string | null): string | null {
  if (!slug) return HOME_TITLE;
  const title = ROUTE_TITLES[slug];
  return title ? `${title} | ${SITE_NAME}` : null;
}

